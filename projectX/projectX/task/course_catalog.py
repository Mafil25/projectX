"""Five exercises per original level; expected results are explicit fixtures."""


def exercise(title, signature, condition, cases):
    function_name = signature.split('(', 1)[0]
    arguments, expected = cases[0]
    example = f"{function_name}({', '.join(repr(value) for value in arguments)}) → {expected!r}"
    return {
        'title': title,
        'function_name': function_name,
        'starter_code': f'def {signature}:\n    pass\n',
        'description': (
            f'Напишите функцию {signature}.\n\n{condition}\n\n'
            f'Верните результат через return. Вывод через print не заменяет return.\n\nПример: {example}'
        ),
        'tests': [{'input': arguments, 'expected': result} for arguments, result in cases],
    }


